#!/bin/bash
# RBE via BuildBuddy for LineageOS 24 (AOSP 17, Siso).
#
# Usage: source build/envsetup.sh && source rbe.sh && lunch ... && m ...
#
# Mode: Siso native REAPI (soong_ui starts `siso proxy`), not reclient.
# In AOSP 17 Soong no longer wraps C/C++ compiles in rewrapper, so the
# reclient mode only ran java/link steps remotely and compiled C++ locally.
#
# Single file, two roles (tree top is not a repo project, so `repo sync`
# leaves it alone):
#   source rbe.sh - sets up the build environment
#   ./rbe.sh      - credential helper for `siso proxy` (RBE_credentials_helper)

BUILDBUDDY_API_KEY="xxx"

# Executed rather than sourced: Soong calls this as the credential helper
# (`<this> <args> --cache_dir ... -bazel_compat`, args ignored). Print the
# API key as gRPC headers in the JSON format siso expects.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    printf '{"headers":{"x-buildbuddy-api-key":["%s"]},"expires":"2099-01-01T00:00:00Z"}\n' \
        "$BUILDBUDDY_API_KEY"
    exit 0
fi

if [ -z "$BUILDBUDDY_API_KEY" ] || [ "$BUILDBUDDY_API_KEY" = "xxx" ]; then
    echo "rbe.sh: BUILDBUDDY_API_KEY is not set, building without RBE" >&2
    unset BUILDBUDDY_API_KEY
    return 0 2>/dev/null || exit 0
fi

_rbe_top=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

# Siso config extension. Soong links SISO_CONFIG_DIR as
# out/siso_config/extension and runs it after build/soong/siso_config.
_rbe_siso_dir=$_rbe_top/out/.rbe-siso
mkdir -p "$_rbe_siso_dir"
cat > "$_rbe_siso_dir/main.star" <<'EOF'
# Generated by rbe.sh, edit it there.
load("@builtin//struct.star", "module")

def __step_config(ctx, vars, step_config):
    # AOSP sends java actions (javac, d8, r8, metalava, ...) to the "java16"
    # pool. BuildBuddy has no such pool: those actions wait for the rule
    # timeout (up to 8m) and then fall back to local. Use the default pool.
    platforms = step_config.get("platforms", {})
    if "java16" in platforms and "default" in platforms:
        platforms["java16"]["Pool"] = platforms["default"]["Pool"]
    return step_config

def __filegroups(ctx, vars, filegroups):
    return filegroups

def __handlers(ctx, vars, handlers):
    return handlers

extension = module(
    "extension",
    step_config = __step_config,
    filegroups = __filegroups,
    handlers = __handlers,
)
EOF

export USE_RBE=1
export USE_REWRAPPER=false
export RBE_service=remote.buildbuddy.io:443
export RBE_credentials_helper=$_rbe_top/rbe.sh
export SISO_CONFIG_DIR=$_rbe_siso_dir

# BuildBuddy free tier: 80 remote cores.
export NINJA_REMOTE_NUM_JOBS=80

unset _rbe_top _rbe_siso_dir BUILDBUDDY_API_KEY
